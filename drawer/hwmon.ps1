param(
    [int]$Interval = 2
)
$mtx = New-Object System.Threading.Mutex($false, 'Global\DesktopPage_hwmon')
if (-not $mtx.WaitOne(0)) { exit 0 }
$pidFile = Join-Path $env:LOCALAPPDATA 'DesktopPage\hwmon.pid'
[System.IO.File]::WriteAllText($pidFile, "$PID")
$ErrorActionPreference = 'SilentlyContinue'

# 壁纸目录解析顺序（与 dsh-agent.ps1、DesktopPage.ahk 的 FindWallpaperDir() 保持一致）：
#   1) 环境变量 DSH_WALLPAPER（手动覆盖）
#   2) Lively 的 WallpaperLayout.json 里「当前正应用」的那份 —— 唯一权威来源
#   3) Lively 库里含 dsh.js 的最新一份
#   4) 兜底 dsqq0001.ab1
# 不要写死目录名：install.ps1 允许装成任意名字，机器上也可能同时有多份副本。
function Resolve-WallpaperDir {
    $e = $env:DSH_WALLPAPER
    if ($e -and (Test-Path (Join-Path $e 'index.html'))) { return $e }
    $libBase = Join-Path $env:LOCALAPPDATA 'Lively Wallpaper'
    try {
        $lay = Join-Path $libBase 'WallpaperLayout.json'
        if (Test-Path $lay) {
            $j = [System.IO.File]::ReadAllText($lay, [System.Text.Encoding]::UTF8) | ConvertFrom-Json
            foreach ($it in @($j)) {
                $p = [string]$it.LivelyInfoPath
                if ($p -and (Test-Path (Join-Path $p 'dsh.js'))) { return $p }
            }
        }
    } catch { }
    $best = ''
    $bestTs = [datetime]::MinValue
    try {
        $base = Join-Path $libBase 'Library\wallpapers'
        foreach ($d in (Get-ChildItem $base -Directory -ErrorAction Stop)) {
            if (-not (Test-Path (Join-Path $d.FullName 'dsh.js'))) { continue }
            if ($d.LastWriteTime -gt $bestTs) { $best = $d.FullName; $bestTs = $d.LastWriteTime }
        }
    } catch { }
    if (-not $best) { $best = Join-Path $libBase 'Library\wallpapers\dsqq0001.ab1' }
    return $best
}
$dir = Resolve-WallpaperDir
$outFile = Join-Path $dir 'hw-data.js'
$tmpFile = Join-Path $dir 'hw-data.tmp'

try {
    $proc = Get-CimInstance Win32_Processor | Select-Object -First 1
    $rawCpu = "$($proc.Name)".Trim()
    $cores = "$($proc.NumberOfLogicalProcessors) 线程"
    $osInfo = Get-CimInstance Win32_OperatingSystem
    $boot = $osInfo.LastBootUpTime
    $rawOs = "$($osInfo.Caption)".Trim()
} catch {
    $rawCpu = 'CPU'
    $cores = ''
    $rawOs = 'Windows'
    $boot = (Get-Date)
}

# CPU 型号压缩：i7-12650H 之类保留，其余去掉厂商前缀与多余空格
$cpuShort = $rawCpu
if ($rawCpu -match '(i[3579]-\d{4,5}[A-Z]*)') {
    $cpuShort = $matches[1]
} else {
    $cpuShort = ($rawCpu -replace '\(R\)|\(TM\)|CPU|@.*$', '' -replace '\s+', ' ').Trim()
    if ($cpuShort.Length -gt 26) { $cpuShort = $cpuShort.Substring(0, 26) }
}

# GPU：优先 nvidia-smi（快且准），否则用 WMI 列表
$gpuShort = 'GPU'
$hasSmi = Test-Path 'C:\Windows\System32\nvidia-smi.exe'
if ($hasSmi) {
    $line = & 'C:\Windows\System32\nvidia-smi.exe' --query-gpu=name --format=csv,noheader 2>$null | Select-Object -First 1
    if ($line) {
        $gpuShort = ($line -replace 'NVIDIA\s+', '' -replace 'GeForce\s+', '' -replace '\s+GPU', '').Trim()
    }
} else {
    $vids = @(Get-CimInstance Win32_VideoController | Select-Object -ExpandProperty Name)
    if ($vids.Count -gt 0) {
        $gpuShort = ($vids -join ' + ' -replace 'Intel\(R\)\s*', '' -replace 'NVIDIA\s+', '' -replace '\s+Graphics', '')
        if ($gpuShort.Length -gt 30) { $gpuShort = $gpuShort.Substring(0, 30) }
    }
}

# 系统名压缩
$osShort = $rawOs -replace 'Microsoft\s+', '' -replace '\s*中文版$', ''
if ($osShort.Length -gt 18) { $osShort = $osShort.Substring(0, 18) }

$memTotal = [math]::Round((Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory / 1GB, 1)
$memText = "$memTotal GB"

function ConvertTo-JsString([string]$s) {
    if ($null -eq $s) { return '' }
    return ($s -replace '\\', '\\\\' -replace "'", "\'" -replace "`r", ' ' -replace "`n", ' ')
}

while ($true) {
    $cpuLoad = 0
    try {
        $perf = Get-CimInstance Win32_PerfFormattedData_PerfOS_Processor -Filter "Name='_Total'" |
            Select-Object -First 1
        if ($perf) { $cpuLoad = [double]$perf.PercentProcessorTime }
    } catch { }

    $gpuLoad = 0
    if ($hasSmi) {
        try {
            $v = & 'C:\Windows\System32\nvidia-smi.exe' --query-gpu=utilization.gpu --format=csv,noheader,nounits 2>$null |
                Select-Object -First 1
            if ($v) { $gpuLoad = [double]$v }
        } catch { }
    }

    $up = (Get-Date) - $boot
    $upText = '{0} D {1:D2} H {2:D2} M' -f [int]$up.TotalDays, $up.Hours, $up.Minutes

    $ts = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
    $js = "/* generated by hwmon.ps1 */`nwindow.__HW = { ts: $ts, cpu: $([math]::Round($cpuLoad,1)), gpu: $([math]::Round($gpuLoad,1)), cpuName: '$(ConvertTo-JsString $cpuShort)', gpuName: '$(ConvertTo-JsString $gpuShort)', os: '$(ConvertTo-JsString $osShort)', uptime: '$(ConvertTo-JsString $upText)', cores: '$(ConvertTo-JsString $cores)', mem: '$(ConvertTo-JsString $memText)' };`n"

    try {
        [System.IO.File]::WriteAllText($tmpFile, $js, (New-Object System.Text.UTF8Encoding($false)))
        Move-Item -LiteralPath $tmpFile -Destination $outFile -Force
    } catch { }

    Start-Sleep -Seconds $Interval
}
